/**
 * AI 이미지 생성 로딩 별 애니메이션
 * 피그마 메이크의 SparkleStars를 motion 없이 CSS/JS로 구현
 */
export function SparkleStars() {
  const [frameProgress, setFrameProgress] = useState(0);

  // requestAnimationFrame을 사용한 부드러운 프레임 애니메이션
  useEffect(() => {
    const frameDuration = 400; // 프레임당 400ms
    const totalDuration = frameDuration * starFrames.length;
    const startTime = Date.now();

    let animationId: number;

    const animate = () => {
      const elapsed = Date.now() - startTime;
      const progress = (elapsed % totalDuration) / totalDuration;
      setFrameProgress(progress * starFrames.length);
      animationId = requestAnimationFrame(animate);
    };

    animationId = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(animationId);
  }, []);

  // 부드러운 이징 함수
  const easeInOutCubic = (t: number) => {
    return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
  };

  // 프레임별 opacity 계산 (부드러운 크로스페이드)
  const getFrameOpacity = (frameIndex: number) => {
    const blendWidth = 1.2; // 넓은 블렌딩으로 부드러운 전환

    let distance = Math.abs(frameProgress - frameIndex);

    // 루프 처리
    if (distance > starFrames.length / 2) {
      distance = starFrames.length - distance;
    }

    if (distance < blendWidth) {
      const t = distance / blendWidth;
      return 1 - easeInOutCubic(t);
    }

    return 0;
  };

  return (
    <div
      className="absolute top-1/2 left-1/2"
      style={{
        width: '85px',
        height: '85px',
        transform: 'translate(-50%, -50%)',
      }}
    >
      {/* scale 애니메이션 wrapper */}
      <div
        className="size-full"
        style={{
          animation: 'sparkle-stars-scale 3s ease-in-out infinite',
        }}
      >
        <svg
          className="block size-full"
          fill="none"
          viewBox="15 5 120 140"
          style={{
            filter: 'drop-shadow(0 0 10px rgba(255, 206, 72, 0.5))',
          }}
        >
          {/* 모든 프레임을 동시에 렌더링하고 크로스페이드 */}
          {starFrames.map((frame, frameIndex) => {
            const opacity = getFrameOpacity(frameIndex);

            return (
              <g
                key={frameIndex}
                style={{
                  opacity,
                  transition: 'opacity 0.05s linear',
                }}
              >
                {frame.paths.map((path, pathIndex) => (
                  <path
                    key={pathIndex}
                    d={path.d}
                    fill={`url(#grad${frameIndex}_${pathIndex})`}
                    opacity={path.opacity}
                  />
                ))}
              </g>
            );
          })}

          <defs>
            {/* 모든 path에 대한 그라데이션 */}
            {starFrames.map((frame, frameIndex) =>
              frame.paths.map((_, pathIndex) => (
                <linearGradient
                  key={`${frameIndex}_${pathIndex}`}
                  gradientUnits="userSpaceOnUse"
                  id={`grad${frameIndex}_${pathIndex}`}
                  x1="75"
                  x2="75"
                  y1="20"
                  y2="130"
                >
                  <stop stopColor="#FFBB00" />
                  <stop offset="0.22" stopColor="#FFFFFF" />
                  <stop offset="1" stopColor="#FFCE48" />
                </linearGradient>
              )),
            )}
          </defs>
        </svg>
      </div>
    </div>
  );
}
